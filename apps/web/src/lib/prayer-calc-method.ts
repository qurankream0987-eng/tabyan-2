/** الطريقة الاحتياطية عند تعذّر معرفة البلد */
export const FALLBACK_METHOD = 3;

export function getCalcMethod(countryCode?: string | null): CalcMethod {
  const cc = (countryCode ?? "").trim().toUpperCase();
  const method = COUNTRY_METHODS[cc] ?? FALLBACK_METHOD;
  return { method, label: METHOD_LABELS[method] ?? METHOD_LABELS[FALLBACK_METHOD] };
}
