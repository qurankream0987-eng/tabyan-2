/**
 * Regenerates src/quran/layout/pageFirstWord.generated.ts from the QCF page
 * data in artifacts/tabyan/public/mushaf/pages. Read-only for the page data.
 *
 *   npx tsx smart-mushaf-v3/scripts/gen-page-word-index.ts   (from artifacts/tabyan)
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { buildPageFirstWords, QcfPageSource, TOTAL_MUSHAF_PAGES } from '../src/quran/layout/pageFirstWordBuilder';

const here = dirname(fileURLToPath(import.meta.url));
const pagesDir = join(here, '../../public/mushaf/pages');
const pages: QcfPageSource[] = [];
for (let p = 1; p <= TOTAL_MUSHAF_PAGES; p += 1) {
  pages.push(JSON.parse(readFileSync(join(pagesDir, `${p}.json`), 'utf8')));
}
const rows = buildPageFirstWords(pages);
const body = rows.map((row) => `[${row.join(',')}]`).join(',');
writeFileSync(
  join(here, '../src/quran/layout/pageFirstWord.generated.ts'),
  `/** Generated by scripts/gen-page-word-index.ts from QCF page data — do not edit. */\n` +
    `/** First canonical [surah, ayah, wordIndex] of each Madani page; index 0 = page 1. */\n` +
    `export const PAGE_FIRST_WORD: readonly (readonly [number, number, number])[] = [${body}];\n`,
);
console.log(`wrote ${rows.length} page entries`);
