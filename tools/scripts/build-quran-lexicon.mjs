#!/usr/bin/env node
// Builds the word lexicon the Tilawi decoder is constrained to: every distinct
// Quran word, spelled as the recognizer spells it (no harakat, hamza seats and
// alef maqsura folded), from the mushaf word pages. Output is a TS module so
// the API bundle carries it without reading the web assets at runtime.
//
// usage: node tools/scripts/build-quran-lexicon.mjs
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const pages = path.join(root, "apps/web/public/mushaf/quran-words/pages");
const out = path.join(root, "apps/api/src/recitation-providers/tilawi/quranLexicon.ts");

const MARKS = /[ؐ-ًؚ-ٟۖ-ۭـ‌‍‏﻿]/g;
const LETTERS = /^[ء-ي]+$/;
function spell(text, dagger) {
  return text.normalize("NFC").replace(/ٰ/g, dagger).replace(MARKS, "")
    .replace(/[ٱأإآ]/g, "ا").replace(/ى/g, "ي").trim();
}

const words = new Set();
for (let page = 1; page <= 604; page += 1) {
  const { words: pageWords } = JSON.parse(readFileSync(path.join(pages, `${page}.json`), "utf8"));
  for (const word of pageWords) {
    // The dagger alef is spoken; the recognizer writes it as a plain alef or not at all.
    for (const dagger of ["ا", ""]) {
      for (const token of spell(word.displayText, dagger).split(/\s+/)) {
        if (!token || !LETTERS.test(token)) continue;
        words.add(token);
        // The mushaf writes madda as hamza + alef ("ءامنوا"); the recognizer writes "آمنوا".
        if (token.includes("ءا")) words.add(token.replace(/ءا/g, "ا"));
      }
    }
  }
}
const sorted = [...words].sort();
writeFileSync(out, `// Generated by tools/scripts/build-quran-lexicon.mjs; do not edit.\n/** Every distinct Quran word as the recognizer spells it, space-separated. */\nexport const QURAN_LEXICON = ${JSON.stringify(sorted.join(" "))};\n`);
console.log(`${sorted.length} words -> ${path.relative(root, out)}`);
